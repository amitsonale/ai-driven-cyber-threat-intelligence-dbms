-- AI-Driven Cyber Threat Intelligence & Attack Campaign Correlation System
-- Reconstructed relational schema for PostgreSQL; run in a fresh database.

CREATE TABLE organization (
    org_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name            VARCHAR(160) NOT NULL UNIQUE,
    industry        VARCHAR(100),
    headquarters    VARCHAR(120),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE app_user (
    user_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name       VARCHAR(160) NOT NULL,
    email           VARCHAR(254) NOT NULL UNIQUE,
    role            VARCHAR(40) NOT NULL CHECK (role IN ('Analyst', 'Admin', 'Viewer')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE threat_actor (
    actor_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(160) NOT NULL UNIQUE,
    aliases             TEXT,
    origin_country      VARCHAR(100),
    sophistication      VARCHAR(40) CHECK (sophistication IN ('Low', 'Moderate', 'High', 'Advanced')),
    description         TEXT
);

CREATE TABLE intel_source (
    source_id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(150) NOT NULL UNIQUE,
    source_type         VARCHAR(30) NOT NULL
                        CHECK (source_type IN ('OSINT', 'Commercial', 'ISAC', 'Internal')),
    reliability_score   NUMERIC(3,2) NOT NULL DEFAULT 0.50
                        CHECK (reliability_score >= 0.00 AND reliability_score <= 1.00),
    source_url          TEXT,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE asset (
    asset_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    org_id          INTEGER NOT NULL REFERENCES organization(org_id) ON DELETE RESTRICT,
    hostname        VARCHAR(160) NOT NULL,
    ip_address      INET,
    asset_type      VARCHAR(60) NOT NULL DEFAULT 'Server',
    criticality     VARCHAR(20) NOT NULL CHECK (criticality IN ('Low', 'Medium', 'High', 'Critical')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (org_id, hostname)
);

CREATE TABLE indicator (
    indicator_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id       INTEGER REFERENCES intel_source(source_id) ON DELETE SET NULL,
    ioc_type        VARCHAR(30) NOT NULL CHECK (ioc_type IN ('IP', 'Domain', 'URL', 'Hash', 'Email')),
    value           TEXT NOT NULL,
    confidence_score NUMERIC(5,2) NOT NULL CHECK (confidence_score BETWEEN 0 AND 100),
    first_seen      TIMESTAMPTZ,
    last_seen       TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (first_seen IS NULL OR last_seen IS NULL OR last_seen >= first_seen),
    UNIQUE (ioc_type, value)
);

CREATE TABLE campaign (
    campaign_id        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id           INTEGER REFERENCES threat_actor(actor_id) ON DELETE SET NULL,
    name               VARCHAR(180) NOT NULL UNIQUE,
    objective          TEXT,
    start_date         DATE,
    end_date           DATE,
    status             VARCHAR(30) NOT NULL DEFAULT 'Active'
                       CHECK (status IN ('Active', 'Monitoring', 'Dormant', 'Closed')),
    correlation_score  NUMERIC(5,2) NOT NULL DEFAULT 0
                       CHECK (correlation_score BETWEEN 0 AND 100),
    CHECK (start_date IS NULL OR end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE ttp (
    ttp_id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    technique_id        VARCHAR(20) NOT NULL UNIQUE,
    name                VARCHAR(180) NOT NULL,
    tactic              VARCHAR(100) NOT NULL,
    description         TEXT
);

CREATE TABLE malware_sample (
    malware_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sha256_hash     CHAR(64) NOT NULL UNIQUE,
    family_name     VARCHAR(140) NOT NULL,
    file_type       VARCHAR(40),
    first_seen      DATE
);

CREATE TABLE vulnerability (
    vulnerability_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cve_id           VARCHAR(20) NOT NULL UNIQUE,
    cvss_score       NUMERIC(3,1) CHECK (cvss_score BETWEEN 0 AND 10),
    description      TEXT,
    published_on     DATE
);

CREATE TABLE alert (
    alert_id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asset_id            INTEGER NOT NULL REFERENCES asset(asset_id) ON DELETE CASCADE,
    indicator_id        INTEGER NOT NULL REFERENCES indicator(indicator_id) ON DELETE RESTRICT,
    assigned_user_id    INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    severity            VARCHAR(20) NOT NULL CHECK (severity IN ('Low', 'Medium', 'High', 'Critical')),
    status              VARCHAR(30) NOT NULL DEFAULT 'Open'
                        CHECK (status IN ('Open', 'Investigating', 'Resolved', 'False Positive')),
    detected_at         TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details             TEXT,
    UNIQUE (asset_id, indicator_id, detected_at)
);

CREATE TABLE report (
    report_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    campaign_id     INTEGER REFERENCES campaign(campaign_id) ON DELETE SET NULL,
    title           VARCHAR(220) NOT NULL,
    summary         TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Associative relations for many-to-many relationships.
CREATE TABLE campaign_indicator (
    campaign_id     INTEGER NOT NULL REFERENCES campaign(campaign_id) ON DELETE CASCADE,
    indicator_id    INTEGER NOT NULL REFERENCES indicator(indicator_id) ON DELETE CASCADE,
    linked_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (campaign_id, indicator_id)
);

CREATE TABLE campaign_ttp (
    campaign_id     INTEGER NOT NULL REFERENCES campaign(campaign_id) ON DELETE CASCADE,
    ttp_id          INTEGER NOT NULL REFERENCES ttp(ttp_id) ON DELETE CASCADE,
    PRIMARY KEY (campaign_id, ttp_id)
);

CREATE TABLE indicator_malware (
    indicator_id    INTEGER NOT NULL REFERENCES indicator(indicator_id) ON DELETE CASCADE,
    malware_id      INTEGER NOT NULL REFERENCES malware_sample(malware_id) ON DELETE CASCADE,
    PRIMARY KEY (indicator_id, malware_id)
);

CREATE TABLE malware_vuln (
    malware_id       INTEGER NOT NULL REFERENCES malware_sample(malware_id) ON DELETE CASCADE,
    vulnerability_id INTEGER NOT NULL REFERENCES vulnerability(vulnerability_id) ON DELETE CASCADE,
    PRIMARY KEY (malware_id, vulnerability_id)
);

-- Status audit trail maintained by a trigger in 05_functions_procedures_triggers.sql.
CREATE TABLE alert_status_history (
    history_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alert_id        INTEGER NOT NULL REFERENCES alert(alert_id) ON DELETE CASCADE,
    old_status      VARCHAR(30),
    new_status      VARCHAR(30) NOT NULL,
    changed_by      INTEGER REFERENCES app_user(user_id) ON DELETE SET NULL,
    changed_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
